/// This is a trait for the main entry point of the RPC, it describes the types for client,
/// request and response
pub trait Rpc: Sized {
    /// Returns the name of this service
    fn service_name() -> &'static str;
}

/// Represents a [Rpc] which can be served by `Server`
pub trait RpcWithServer<Server, Runtime: AsyncRuntime, F: IsFormat>: Rpc {
    /// The handler type for this server
    type Handler: Handler<Runtime> + 'static;
    /// Create a new handler from the given server
    fn handler(server: Server, format: F) -> Self::Handler;
}

/// This trait describes a handler which takes a request and calls the appropriate method of
/// an underlying server implementation, then builds and returns the response
///
/// It also handles converting [`StreamID`](connection::message::StreamID)s into [`impl Stream`](Stream)
///
/// Implementations are generated by the `#[rpc]` macro
pub trait Handler<R: AsyncRuntime>: Send + Sync + 'static {
    /// takes the request and returns a response, see [trait documentation](Self) for details
    fn handle(
        &self,
        request_id: RequestID,
        method_id: MethodID,
        request: Vec<u8>,
        stream_handler: ServiceManager<R>,
        guard: TeardownGuard,
    ) -> BoxFuture<'_, Result<Vec<u8>, HandleError>>;
}

/// Represents a server implementation that can easily be converted into a [`Handler`]
pub trait IntoHandler<R, Runtime: AsyncRuntime, F> {
    /// Wrap this server in the appropriate Handler type
    fn into_handler(self, format: F) -> impl Handler<Runtime> + 'static;
}

impl<Server, R, Runtime, F> IntoHandler<R, Runtime, F> for Server
where
    R: RpcWithServer<Server, Runtime, F>,
    Runtime: AsyncRuntime,
    F: IsFormat,
{
    fn into_handler(self, format: F) -> impl Handler<Runtime> + 'static {
        R::handler(self, format)
    }
}

