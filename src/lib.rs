/// This is a trait for the main entry point of the RPC, it provides function for creating server and client
pub trait Service: Sized + Send + Sync + 'static {
    /// The client type for this service
    type Client<F: Format>;

    /// Create a new client for this service
    fn client<F: Format>(client: Client<Self>, format: F) -> Self::Client<F>;

    /// Returns the name of this service
    fn service_name() -> &'static str;
}

/// Represents a [Service] which can be served by `Server`
pub trait ServiceWithServer<Server, F: Format>: Service {
    /// The handler type for this server
    type Handler: Handler + 'static;
    /// Create a new handler from the given server
    fn handler(server: Server, format: F) -> Self::Handler;
}

/// This trait describes a handler which takes a request and calls the appropriate method of
/// an underlying server implementation, then builds and returns the response
///
/// It also handles converting [`StreamID`](connection::message::StreamID)s into [`impl Stream`](Stream)
///
/// Implementations are generated by the [`#[service]`](crate::service) macro
pub trait Handler: Send + Sync + 'static {
    /// takes the request and returns a response, see [trait documentation](Self) for details
    fn handle(
        &self,
        request_id: RequestID,
        method_id: MethodID,
        request: Vec<u8>,
        stream_handler: ServiceManager,
        guard: TeardownGuard,
    ) -> impl Future<Output = Result<Vec<u8>, HandleError>> + Send + '_;
}

/// Represents a server implementation that can easily be converted into a [`Handler`]
pub trait IntoHandler<R, F>: Send + 'static {
    /// Wrap this server in the appropriate Handler type
    fn into_handler(self, format: F) -> impl Handler + 'static;
}

impl<Server, S, F> IntoHandler<S, F> for Server
where
    Server: Send + 'static,
    S: ServiceWithServer<Server, F>,
    F: Format,
{
    fn into_handler(self, format: F) -> impl Handler + 'static {
        S::handler(self, format)
    }
}

